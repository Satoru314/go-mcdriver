// generate は inDir（公式データ出力の generated フォルダ）と jar の version.json を読み、outDir に *_gen.go を書く。
func generate(version, inDir, outDir, jarPath string) error {
	reports := filepath.Join(inDir, "reports")

	regs, err := loadRegistries(filepath.Join(reports, "registries.json"))
	if err != nil {
		return err
	}
	blocks, err := loadBlocks(filepath.Join(reports, "blocks.json"), regs)
	if err != nil {
		return err
	}
	items, err := loadItems(filepath.Join(reports, "items.json"), regs)
	if err != nil {
		return err
	}
	blockIndex := map[string]int{}
	for _, b := range blocks {
		blockIndex[b.Name] = b.ID
	}
	itemIndex := map[string]int{}
	for _, it := range items {
		itemIndex[it.Name] = it.ID
	}
	tagDir := filepath.Join(inDir, "data", "minecraft", "tags")
	blockTags, err := loadTags(filepath.Join(tagDir, "block"), blockIndex)
	if err != nil {
		return fmt.Errorf("ブロックのタグ: %w", err)
	}
	itemTags, err := loadTags(filepath.Join(tagDir, "item"), itemIndex)
	if err != nil {
		return fmt.Errorf("アイテムのタグ: %w", err)
	}
	// アイテムの道具の規則が指すブロックとタグがあるか確かめる
	for _, it := range items {
		if it.Tool == nil {
			continue
		}
		for _, r := range it.Tool.Rules {
			if r.Tag != "" {
				if _, ok := blockTags[r.Tag]; !ok {
					return fmt.Errorf("%s の道具の規則: タグ #%s がない", it.Name, r.Tag)
				}
			}
			for _, n := range r.Blocks {
				if _, ok := blockIndex[n]; !ok {
					return fmt.Errorf("%s の道具の規則: ブロック %s がない", it.Name, n)
				}
			}
		}
	}
	recipes, err := loadRecipes(filepath.Join(inDir, "data", "minecraft", "recipe"), itemIndex, itemTags)
	if err != nil {
		return fmt.Errorf("レシピ: %w", err)
	}
	packets, err := loadPackets(filepath.Join(reports, "packets.json"))
	if err != nil {
		return err
	}
	ver, err := loadVersionJSON(jarPath)
	if err != nil {
		return err
	}
	if ver.ID != version {
		return fmt.Errorf("jar の version.json のバージョン %q が指定 %q と違う", ver.ID, version)
	}

	files := map[string]func(*bytes.Buffer){
		"version_gen.go":    func(w *bytes.Buffer) { writeVersion(w, ver) },
		"blocks_gen.go":     func(w *bytes.Buffer) { writeBlocks(w, blocks) },
		"items_gen.go":      func(w *bytes.Buffer) { writeItems(w, items, blockIndex) },
		"tags_gen.go":       func(w *bytes.Buffer) { writeTags(w, blockTags, itemTags) },
		"recipes_gen.go":    func(w *bytes.Buffer) { writeRecipes(w, recipes) },
		"packets_gen.go":    func(w *bytes.Buffer) { writePackets(w, packets) },
		"registries_gen.go": func(w *bytes.Buffer) { writeRegistries(w, regs) },
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, name := range names {
		var buf bytes.Buffer
		buf.WriteString("// Code generated by cmd/gendata from the Minecraft " + version + " server data generator. DO NOT EDIT.\n\n")
		buf.WriteString("package data\n\n")
		files[name](&buf)
		src, err := format.Source(buf.Bytes())
		if err != nil {
			return fmt.Errorf("%s の整形: %w", name, err)
		}
		if err := os.WriteFile(filepath.Join(outDir, name), src, 0o644); err != nil {
			return err
		}
		fmt.Printf("書き出し: %s（%d バイト）\n", filepath.Join(outDir, name), len(src))
	}
	fmt.Printf("ブロック %d, アイテム %d, ブロックのタグ %d, アイテムのタグ %d, レシピ %d, registry %d, パケット %d\n",
		len(blocks), len(items), len(blockTags), len(itemTags), len(recipes), len(regs), len(packets))
	return nil
}

// ---- 名前 ----

// stripNS は "minecraft:" を外す。ほかの名前空間はエラーにする（バニラのデータしか想定しない）。
func stripNS(s string) string {
	if rest, ok := strings.CutPrefix(s, "minecraft:"); ok {
		return rest
	}
	panic(fmt.Sprintf("minecraft 以外の名前空間: %q", s))
}

func readJSON(path string, v any) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(b, v); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

// ---- registry ----

type registry struct {
	Name    string
	Default string
	Entries []string // protocol_id の順
}

func loadRegistries(path string) ([]registry, error) {
	var raw map[string]struct {
		Default string `json:"default"`
		Entries map[string]struct {
			ProtocolID int `json:"protocol_id"`
		} `json:"entries"`
	}
	if err := readJSON(path, &raw); err != nil {
		return nil, err
	}
	var regs []registry
	for name, r := range raw {
		reg := registry{Name: stripNS(name), Entries: make([]string, len(r.Entries))}
		if r.Default != "" {
			reg.Default = stripNS(r.Default)
		}
		for e, v := range r.Entries {
			if v.ProtocolID < 0 || v.ProtocolID >= len(r.Entries) || reg.Entries[v.ProtocolID] != "" {
				return nil, fmt.Errorf("registry %s: protocol_id %d が飛んでいるか重なっている", name, v.ProtocolID)
			}
			// command_argument_type には "brigadier:" の項目があるので、"minecraft:" だけを外す
			reg.Entries[v.ProtocolID] = strings.TrimPrefix(e, "minecraft:")
		}
		regs = append(regs, reg)
	}
	sort.Slice(regs, func(i, j int) bool { return regs[i].Name < regs[j].Name })
	return regs, nil
}

func findRegistry(regs []registry, name string) []string {
	for _, r := range regs {
		if r.Name == name {
			return r.Entries
		}
	}
	return nil
}

// ---- ブロック ----

type property struct {
	Name   string
	Values []string
}

type block struct {
	ID           int
	Name         string
	Type         string
	Properties   []property
	MinState     int
	NumStates    int
	DefaultState int
}

func loadBlocks(path string, regs []registry) ([]block, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var raw map[string]struct {
		Definition struct {
			Type string `json:"type"`
		} `json:"definition"`
		Properties map[string][]string `json:"properties"`
		States     []struct {
			ID         int               `json:"id"`
			Default    bool              `json:"default"`
			Properties map[string]string `json:"properties"`
		} `json:"states"`
	}
	if err := json.Unmarshal(b, &raw); err != nil {
		return nil, err
	}
	reg := findRegistry(regs, "block")
	if len(reg) != len(raw) {
		return nil, fmt.Errorf("blocks.json のブロック数 %d と registry の数 %d が違う", len(raw), len(reg))
	}
	var blocks []block
	nextState := 0
	for id, name := range reg {
		r, ok := raw["minecraft:"+name]
		if !ok {
			return nil, fmt.Errorf("registry のブロック %s が blocks.json にない", name)
		}
		bl := block{ID: id, Name: name, Type: stripNS(r.Definition.Type), DefaultState: -1}
		// 状態 ID の並びは、プロパティを名前の順に並べたものになる（ゲームの中で名前順の map に入っているため。
		// reports の properties のキーの順とは違うことがある。例 piston_head）。下で全状態について確かめる
		keys := make([]string, 0, len(r.Properties))
		for k := range r.Properties {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			bl.Properties = append(bl.Properties, property{Name: k, Values: r.Properties[k]})
		}
		n := 1
		for _, p := range bl.Properties {
			n *= len(p.Values)
		}
		if len(r.States) != n {
			return nil, fmt.Errorf("%s: 状態の数 %d がプロパティの組み合わせの数 %d と違う", name, len(r.States), n)
		}
		bl.MinState, bl.NumStates = nextState, n
		// 状態 ID = MinState + 各プロパティの値の番号を、名前順で最初のプロパティを最上位として並べた数
		for _, s := range r.States {
			idx := 0
			for _, p := range bl.Properties {
				vi := indexOf(p.Values, s.Properties[p.Name])
				if vi < 0 {
					return nil, fmt.Errorf("%s: 状態 %d のプロパティ %s=%q が一覧にない", name, s.ID, p.Name, s.Properties[p.Name])
				}
				idx = idx*len(p.Values) + vi
			}
			if s.ID != bl.MinState+idx {
				return nil, fmt.Errorf("%s: 状態 %d の ID が計算 %d と合わない", name, s.ID, bl.MinState+idx)
			}
			if s.Default {
				if bl.DefaultState >= 0 {
					return nil, fmt.Errorf("%s: 既定の状態が2つある", name)
				}
				bl.DefaultState = s.ID
			}
		}
		if bl.DefaultState < 0 {
			return nil, fmt.Errorf("%s: 既定の状態がない", name)
		}
		nextState += n
		blocks = append(blocks, bl)
	}
	return blocks, nil
}

func indexOf(list []string, s string) int {
	for i, v := range list {
		if v == s {
			return i
		}
	}
	return -1
}

// ---- アイテム ----

type toolRule struct {
	Tag             string   // "#" を外したブロックのタグ（タグで指すとき）
	Blocks          []string // ブロックの名前（直接指すとき）
	Speed           *float64
	CorrectForDrops *bool
}

type tool struct {
	Rules              []toolRule
	DefaultMiningSpeed *float64
	DamagePerBlock     *int
}

type food struct {
	Nutrition    int
	Saturation   float64
	CanAlwaysEat bool
}

type consumable struct {
	ConsumeSeconds *float64
	Animation      string
}

type item struct {
	ID           int
	Name         string
	MaxStackSize int
	MaxDamage    int
	Food         *food
	Consumable   *consumable
	Tool         *tool
}

func loadItems(path string, regs []registry) ([]item, error) {
	var raw map[string]struct {
		Components map[string]json.RawMessage `json:"components"`
	}
	if err := readJSON(path, &raw); err != nil {
		return nil, err
	}
	reg := findRegistry(regs, "item")
	if len(reg) != len(raw) {
		return nil, fmt.Errorf("items.json のアイテム数 %d と registry の数 %d が違う", len(raw), len(reg))
	}
	var items []item
	for id, name := range reg {
		r, ok := raw["minecraft:"+name]
		if !ok {
			return nil, fmt.Errorf("registry のアイテム %s が items.json にない", name)
		}
		it := item{ID: id, Name: name}
		c := r.Components
		if v, ok := c["minecraft:max_stack_size"]; ok {
			if err := json.Unmarshal(v, &it.MaxStackSize); err != nil {
				return nil, err
			}
		} else {
			return nil, fmt.Errorf("%s: max_stack_size がない", name)
		}
		if v, ok := c["minecraft:max_damage"]; ok {
			if err := json.Unmarshal(v, &it.MaxDamage); err != nil {
				return nil, err
			}
		}
		if v, ok := c["minecraft:food"]; ok {
			var f struct {
				Nutrition    *int     `json:"nutrition"`
				Saturation   *float64 `json:"saturation"`
				CanAlwaysEat bool     `json:"can_always_eat"`
			}
			if err := json.Unmarshal(v, &f); err != nil {
				return nil, err
			}
			if f.Nutrition == nil || f.Saturation == nil {
				return nil, fmt.Errorf("%s: food に nutrition か saturation がない", name)
			}
			it.Food = &food{Nutrition: *f.Nutrition, Saturation: *f.Saturation, CanAlwaysEat: f.CanAlwaysEat}
		}
		if v, ok := c["minecraft:consumable"]; ok {
			var cs struct {
				ConsumeSeconds *float64 `json:"consume_seconds"`
				Animation      string   `json:"animation"`
			}
			if err := json.Unmarshal(v, &cs); err != nil {
				return nil, err
			}
			it.Consumable = &consumable{ConsumeSeconds: cs.ConsumeSeconds, Animation: cs.Animation}
		}
		if v, ok := c["minecraft:tool"]; ok {
			var t struct {
				Rules []struct {
					Blocks          json.RawMessage `json:"blocks"`
					Speed           *float64        `json:"speed"`
					CorrectForDrops *bool           `json:"correct_for_drops"`
				} `json:"rules"`
				DefaultMiningSpeed *float64 `json:"default_mining_speed"`
				DamagePerBlock     *int     `json:"damage_per_block"`
			}
			if err := json.Unmarshal(v, &t); err != nil {
				return nil, err
			}
			tl := &tool{DefaultMiningSpeed: t.DefaultMiningSpeed, DamagePerBlock: t.DamagePerBlock}
			for _, rr := range t.Rules {
				rule := toolRule{Speed: rr.Speed, CorrectForDrops: rr.CorrectForDrops}
				var one string
				var list []string
				if json.Unmarshal(rr.Blocks, &one) == nil {
					if tag, ok := strings.CutPrefix(one, "#"); ok {
						rule.Tag = stripNS(tag)
					} else {
						rule.Blocks = []string{stripNS(one)}
					}
				} else if err := json.Unmarshal(rr.Blocks, &list); err == nil {
					for _, s := range list {
						rule.Blocks = append(rule.Blocks, stripNS(s))
					}
				} else {
					return nil, fmt.Errorf("%s: 道具の規則の blocks が読めない: %s", name, rr.Blocks)
				}
				tl.Rules = append(tl.Rules, rule)
			}
			it.Tool = tl
		}
		items = append(items, it)
	}
	return items, nil
}

// ---- タグ ----

// loadTags は dir 以下のタグを読み、ほかのタグへの参照（#...）を展開して、ID の一覧（昇順）を返す。
func loadTags(dir string, index map[string]int) (map[string][]int, error) {
	raw := map[string][]string{}
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".json") {
			return err
		}
		rel, _ := filepath.Rel(dir, path)
		name := strings.TrimSuffix(filepath.ToSlash(rel), ".json")
		var t struct {
			Values []string `json:"values"`
		}
		if err := readJSON(path, &t); err != nil {
			return err
		}
		raw[name] = t.Values
		return nil
	})
	if err != nil {
		return nil, err
	}
	resolved := map[string][]int{}
	var resolve func(name string, stack map[string]bool) ([]int, error)
	resolve = func(name string, stack map[string]bool) ([]int, error) {
		if r, ok := resolved[name]; ok {
			return r, nil
		}
		vals, ok := raw[name]
		if !ok {
			return nil, fmt.Errorf("タグ %s がない", name)
		}
		if stack[name] {
			return nil, fmt.Errorf("タグ %s が自分を参照している", name)
		}
		stack[name] = true
		seen := map[int]bool{}
		out := []int{}
		add := func(id int) {
			if !seen[id] {
				seen[id] = true
				out = append(out, id)
			}
		}
		for _, v := range vals {
			if tag, ok := strings.CutPrefix(v, "#"); ok {
				sub, err := resolve(stripNS(tag), stack)
				if err != nil {
					return nil, err
				}
				for _, id := range sub {
					add(id)
				}
				continue
			}
			id, ok := index[stripNS(v)]
			if !ok {
				return nil, fmt.Errorf("タグ %s の %s がない", name, v)
			}
			add(id)
		}
		delete(stack, name)
		sort.Ints(out)
		resolved[name] = out
		return out, nil
	}
	for name := range raw {
		if _, err := resolve(name, map[string]bool{}); err != nil {
			return nil, err
		}
	}
	return resolved, nil
}

// ---- レシピ ----

type ingredient struct {
	Tag   string
	Items []int
}

type itemStack struct {
	Item          int
	Count         int
	HasComponents bool
}

type recipe struct {
	Name        string
	Type        string
	Category    string
	Group       string
	Pattern     []string
	Key         map[string]ingredient
	Ingredients []ingredient
	Input       ingredient
	Material    ingredient
	Template    ingredient
	Base        ingredient
	Addition    ingredient
	Result      *itemStack
	Experience  float64
	CookingTime int
}

func loadRecipes(dir string, itemIndex map[string]int, itemTags map[string][]int) ([]recipe, error) {
	ents, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	parseIng := func(raw json.RawMessage) (ingredient, error) {
		if len(raw) == 0 {
			return ingredient{}, nil
		}
		var one string
		var list []string
		if json.Unmarshal(raw, &one) == nil {
			list = []string{one}
		} else if err := json.Unmarshal(raw, &list); err != nil {
			return ingredient{}, fmt.Errorf("材料が読めない: %s", raw)
		}
		var ing ingredient
		for _, s := range list {
			if tag, ok := strings.CutPrefix(s, "#"); ok {
				if len(list) != 1 {
					return ingredient{}, fmt.Errorf("タグとアイテムが混ざった材料: %s", raw)
				}
				ing.Tag = stripNS(tag)
				if _, ok := itemTags[ing.Tag]; !ok {
					return ingredient{}, fmt.Errorf("アイテムのタグ %s がない", s)
				}
				continue
			}
			id, ok := itemIndex[stripNS(s)]
			if !ok {
				return ingredient{}, fmt.Errorf("アイテム %s がない", s)
			}
			ing.Items = append(ing.Items, id)
		}
		return ing, nil
	}
	var out []recipe
	for _, e := range ents {
		if !strings.HasSuffix(e.Name(), ".json") {
			continue
		}
		var r struct {
			Type        string                     `json:"type"`
			Category    string                     `json:"category"`
			Group       string                     `json:"group"`
			Pattern     []string                   `json:"pattern"`
			Key         map[string]json.RawMessage `json:"key"`
			Ingredients []json.RawMessage          `json:"ingredients"`
			Ingredient  json.RawMessage            `json:"ingredient"`
			Input       json.RawMessage            `json:"input"`
			Material    json.RawMessage            `json:"material"`
			Template    json.RawMessage            `json:"template"`
			Base        json.RawMessage            `json:"base"`
			Addition    json.RawMessage            `json:"addition"`
			Result      json.RawMessage            `json:"result"`
			Experience  float64                    `json:"experience"`
			CookingTime int                        `json:"cookingtime"`
		}
		if err := readJSON(filepath.Join(dir, e.Name()), &r); err != nil {
			return nil, err
		}
		name := strings.TrimSuffix(e.Name(), ".json")
		rc := recipe{Name: name, Type: stripNS(r.Type), Category: r.Category, Group: r.Group,
			Pattern: r.Pattern, Experience: r.Experience, CookingTime: r.CookingTime}
		wrap := func(err error) error { return fmt.Errorf("%s: %w", name, err) }
		if len(r.Key) > 0 {
			rc.Key = map[string]ingredient{}
			for k, v := range r.Key {
				if len([]rune(k)) != 1 {
					return nil, wrap(fmt.Errorf("key %q が1文字でない", k))
				}
				ing, err := parseIng(v)
				if err != nil {
					return nil, wrap(err)
				}
				rc.Key[k] = ing
			}
		}
		for _, v := range r.Ingredients {
			ing, err := parseIng(v)
			if err != nil {
				return nil, wrap(err)
			}
			rc.Ingredients = append(rc.Ingredients, ing)
		}
		// 焼く・石切りの "ingredient" と、作り替え（transmute）の "input" はどちらも Input に入れる
		in := r.Ingredient
		if len(in) == 0 {
			in = r.Input
		}
		for _, p := range []struct {
			dst *ingredient
			raw json.RawMessage
		}{{&rc.Input, in}, {&rc.Material, r.Material}, {&rc.Template, r.Template}, {&rc.Base, r.Base}, {&rc.Addition, r.Addition}} {
			ing, err := parseIng(p.raw)
			if err != nil {
				return nil, wrap(err)
			}
			*p.dst = ing
		}
		if len(r.Result) > 0 {
			var id string
			var obj struct {
				ID         string          `json:"id"`
				Count      *int            `json:"count"`
				Components json.RawMessage `json:"components"`
			}
			if json.Unmarshal(r.Result, &id) == nil {
				obj.ID = id
			} else if err := json.Unmarshal(r.Result, &obj); err != nil {
				return nil, wrap(fmt.Errorf("result が読めない: %s", r.Result))
			}
			iid, ok := itemIndex[stripNS(obj.ID)]
			if !ok {
				return nil, wrap(fmt.Errorf("result のアイテム %s がない", obj.ID))
			}
			// count が省略されたときは 1（ItemStack の形式の既定値）
			cnt := 1
			if obj.Count != nil {
				cnt = *obj.Count
			}
			rc.Result = &itemStack{Item: iid, Count: cnt, HasComponents: len(obj.Components) > 0}
		}
		out = append(out, rc)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

// ---- パケット ----

type packet struct {
	State, Direction, Name string
	ID                     int
}

var packetStates = []string{"handshake", "status", "login", "configuration", "play"}

func loadPackets(path string) ([]packet, error) {
	var raw map[string]map[string]map[string]struct {
		ProtocolID *int `json:"protocol_id"`
	}
	if err := readJSON(path, &raw); err != nil {
		return nil, err
	}
	if len(raw) != len(packetStates) {
		return nil, fmt.Errorf("packets.json の状態の数が %d（%d のはず）", len(raw), len(packetStates))
	}
	var out []packet
	for _, st := range packetStates {
		dirs, ok := raw[st]
		if !ok {
			return nil, fmt.Errorf("packets.json に状態 %s がない", st)
		}
		for _, dir := range []string{"clientbound", "serverbound"} {
			var ps []packet
			for name, v := range dirs[dir] {
				if v.ProtocolID == nil {
					return nil, fmt.Errorf("パケット %s/%s/%s に protocol_id がない", st, dir, name)
				}
				ps = append(ps, packet{State: st, Direction: dir, Name: stripNS(name), ID: *v.ProtocolID})
			}
			sort.Slice(ps, func(i, j int) bool { return ps[i].ID < ps[j].ID })
			for i, p := range ps {
				if p.ID != i {
					return nil, fmt.Errorf("パケット %s/%s: ID が 0 から連続していない（%s=%d）", st, dir, p.Name, p.ID)
				}
			}
			out = append(out, ps...)
		}
	}
	return out, nil
}

// ---- version.json（jar の中） ----

type versionJSON struct {
	ID              string `json:"id"`
	Name            string `json:"name"`
	WorldVersion    int    `json:"world_version"`
	ProtocolVersion int    `json:"protocol_version"`
}

func loadVersionJSON(jarPath string) (versionJSON, error) {
	var v versionJSON
	zr, err := zip.OpenReader(jarPath)
	if err != nil {
		return v, fmt.Errorf("jar を開けない: %w", err)
	}
	defer zr.Close()
	f, err := zr.Open("version.json")
	if err != nil {
		return v, fmt.Errorf("jar に version.json がない: %w", err)
	}
	defer f.Close()
	b, err := io.ReadAll(f)
	if err != nil {
		return v, err
	}
	if err := json.Unmarshal(b, &v); err != nil {
		return v, err
	}
	if v.ProtocolVersion == 0 {
		return v, fmt.Errorf("version.json に protocol_version がない")
	}
	return v, nil
}
